// Builds the Telegram Mini App (../index.html) from telegram-template.html.
//
//   npm run build-app
//
// - Map data: tools/map.json if it exists (from `npm run build-map`), otherwise
//   the data already embedded in ../index.html, so a template-only change does
//   not need the world-atlas download.
// - Bot username for the share link: $BOT_USERNAME, otherwise the one in the
//   current ../index.html, otherwise the template's placeholder.
// - Also writes ../backend/content/map-countries.json: the country names that
//   exist on the map (with neighbours). The backend's content validator uses it
//   to make sure every map answer is a country the player can actually tap.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const TEMPLATE = path.join(__dirname, 'telegram-template.html');
const OUT = path.join(ROOT, 'index.html');
const MARK = '/*MAPDATA*/';

const template = fs.readFileSync(TEMPLATE, 'utf8');
if (!template.includes(MARK)) throw new Error(`template has no ${MARK} marker`);
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';

let mapJson;
const mapFile = path.join(__dirname, 'map.json');
if (fs.existsSync(mapFile)) {
  mapJson = fs.readFileSync(mapFile, 'utf8').trim();
} else {
  const start = current.indexOf('const MAP = ');
  const end = current.indexOf(';\n', start);
  if (start < 0 || end < 0) throw new Error('No tools/map.json and no map data in index.html. Run `npm run build-map`.');
  mapJson = current.slice(start + 'const MAP = '.length, end);
}
const map = JSON.parse(mapJson);

const linkRe = /https:\/\/t\.me\/([A-Za-z0-9_]+)\/play/;
const bot = process.env.BOT_USERNAME || (current.match(linkRe) || [])[1] || 'YOUR_BOT_USERNAME';

const html = template
  .replace(MARK, () => mapJson)
  .replace('https://t.me/YOUR_BOT_USERNAME/play', `https://t.me/${bot}/play`);
fs.writeFileSync(OUT, html);

const countries = map.map((c) => ({ name: c.name, neighbours: c.n })).sort((a, b) => a.name.localeCompare(b.name));
fs.writeFileSync(
  path.join(ROOT, 'backend', 'content', 'map-countries.json'),
  JSON.stringify({ _source: 'Generated by tools/build-app.js from the embedded map (Natural Earth 1:110m via world-atlas). Do not edit by hand.', countries }, null, 0) + '\n',
);

console.log(`index.html: ${html.length} bytes, ${map.length} map shapes, bot @${bot}`);
console.log(`backend/content/map-countries.json: ${countries.length} countries`);
